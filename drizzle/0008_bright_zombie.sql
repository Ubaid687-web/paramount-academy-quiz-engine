CREATE TABLE `assessmentPatternProfiles` (
	`id` int AUTO_INCREMENT NOT NULL,
	`patternSourceId` int NOT NULL,
	`sectionAInstruction` text,
	`sectionBInstruction` text,
	`sectionCInstruction` text,
	`mcqCount` int,
	`mcqMarksEach` int,
	`shortOrPairCount` int,
	`shortMarksEach` int,
	`longOrPairCount` int,
	`longMarksEach` int,
	`totalMarks` int,
	`durationMinutes` int,
	`orRule` text,
	`profileEvidenceNotes` longtext,
	`reviewStatus` enum('draft','reviewed','needs_revision') NOT NULL DEFAULT 'draft',
	`reviewedBy` int,
	`reviewedAt` timestamp,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `assessmentPatternProfiles_id` PRIMARY KEY(`id`),
	CONSTRAINT `assessmentPatternProfiles_patternSourceId_unique` UNIQUE(`patternSourceId`)
);
